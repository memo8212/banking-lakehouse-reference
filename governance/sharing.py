"""Render sharing.yaml into Delta Sharing SQL + a share manifest (deterministic)."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SHARING = HERE / "sharing.yaml"


def load_sharing(path: str | Path = SHARING) -> dict:
    return yaml.safe_load(Path(path).read_text())


def render_sharing_sql(sharing: dict) -> str:
    share = sharing["share"]
    recipient = sharing["recipient"]
    lines = ["-- ============================================================",
             "-- Delta Sharing — generated by `python -m governance share`",
             "-- ============================================================", "",
             f"CREATE SHARE IF NOT EXISTS {share};", ""]
    for table in sorted(sharing["tables"]):
        lines.append(f"ALTER SHARE {share} ADD TABLE {table};")
    lines += ["",
              f"CREATE RECIPIENT IF NOT EXISTS {recipient};",
              f"GRANT SELECT ON SHARE {share} TO RECIPIENT {recipient};",
              "",
              "-- Recipient reads (no data copy):",
              f"--   SELECT * FROM {share}.{sharing['tables'][0]};"]
    return "\n".join(lines) + "\n"


def share_manifest(sharing: dict) -> dict:
    tables = sorted(sharing["tables"])
    blob = json.dumps({"share": sharing["share"], "recipient": sharing["recipient"],
                       "tables": tables}, sort_keys=True)
    return {"share": sharing["share"], "recipient": sharing["recipient"],
            "tables": tables, "table_count": len(tables),
            "content_hash": hashlib.sha256(blob.encode()).hexdigest()[:16]}


def apply_sharing(spark, sharing: dict) -> int:
    stmts = [s for s in render_sharing_sql(sharing).split(";") if s.strip()
             and not s.strip().startswith("--")]
    for s in stmts:
        spark.sql(s)
    return len(stmts)
